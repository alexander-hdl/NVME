#!/usr/bin/env python3
"""Generate sim/vectors/rec_cmd_vectors.txt: the exact command strings tools/recorder.py emits
(cmd_* functions, rate/duration conversions) with the parse result expected from rec_cmd_parser.
Line format:  OPNAME SUB NARGS A0 A1 A2 | text      (A0..A2 hex, 16 digits; text = the command line)
Regenerate: python sim/vectors/gen_cmd_vectors.py"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))
import recorder as r  # noqa: E402

rows = []


def add(text, op, sub=0, args=()):
    a = list(args) + [0] * (3 - len(args))
    rows.append("%s %d %d %016X %016X %016X | %s" % (op, sub, len(args), a[0], a[1], a[2], r.check_line(text)))


add(r.cmd_ping(), "OP_PING")
add(r.cmd_stat(), "OP_STAT")
add(r.cmd_cfg(), "OP_CFGQ")
add(r.cmd_res(), "OP_RESQ")
add(r.cmd_prof_q(), "OP_PROFQ")
add(r.cmd_ddr(), "OP_DDRQ")
add(r.cmd_smart_q(), "OP_SMARTQ")
add(r.cmd_stop(), "OP_STOP")
add(r.cmd_pfail(), "OP_PFAIL")
add(r.cmd_abort(), "OP_ABORT")
add(r.cmd_mon(), "OP_MON")
add(r.cmd_dtest(), "OP_DTEST")
add(r.cmd_prof_clr(), "OP_PROF_CLR")
add(r.cmd_format(), "OP_FORMAT")
add(r.cmd_read_last(), "OP_READ_LAST")
add(r.cmd_read_end(), "OP_READ_END")
add(r.cmd_rec(False), "OP_REC")
add(r.cmd_rec(True), "OP_REC_PROF")
for ms in (0, 10, 100, 1000, 0xFFFF):
    add(r.cmd_tel(ms), "OP_TEL", 0, [ms])
for ms in (0, 100, 1000, 0xFFFF):
    add(r.cmd_smart(ms), "OP_SMART", 0, [ms])
add(r.cmd_mode(False), "OP_MODE", 0)
add(r.cmd_mode(True), "OP_MODE", 1)
add(r.cmd_prof_end(False), "OP_PROF_END", 0)
add(r.cmd_prof_end(True), "OP_PROF_END", 1)
for n in (0, 1, 4, 0xFFFF):
    add(r.cmd_prof_rep(n), "OP_PROF_REP", 0, [n])
for mib in (1, 0x20, 0x400):
    add(r.cmd_ddrsz(mib), "OP_DDRSZ", 0, [mib])
for sid in (0, 1, 0x692D3A00, 0xFFFFFFFF):
    add(r.cmd_sid(sid), "OP_SID", 0, [sid])
    add(r.cmd_read_sid(sid), "OP_READ_SID", 0, [sid])
for ln in (0, 1, 8, 0x1000, 0xFFFFFFFF):
    add(r.cmd_len(ln), "OP_LEN", 0, [ln])
for sl in (1, 0x20, 0xADD, 0xBEEF, 0xFFFFFFFF):
    add(r.cmd_read(sl), "OP_READ_N", 0, [sl])
add(r.cmd_memtest(), "OP_MEMTEST")
for mib in (1, 0x20, 0x400):
    add(r.cmd_memtest(mib), "OP_MEMTEST", 0, [mib])

# real rates / durations through the unit conversion of the tool
for rate in ("0", "1MB/s", "50MB/s", "200MB/s", "280MB/s", "800MB/s", "1.59GB/s", "12345B/s"):
    step = r.rate_to_step(r.parse_rate(rate))
    add(r.cmd_rate(step), "OP_RATE", 0, [step])
profile = """# demo
280MB/s 30s
0 500ms
800MB/s 10us
50MB/s 2min
"""
for step, dur in r.parse_profile_text(profile):
    add(r.cmd_prof_add(step, dur), "OP_PROF_ADD", 0, [step, dur])
    add(r.cmd_prof_set(3, step, dur), "OP_PROF_SET", 0, [3, step, dur])
rnd = random.Random(20261124)
for _ in range(24):
    step = rnd.getrandbits(32)
    dur = rnd.randint(1, r.DUR_MAX)
    i = rnd.randrange(64)
    add(r.cmd_prof_add(step, dur), "OP_PROF_ADD", 0, [step, dur])
    add(r.cmd_prof_set(i, step, dur), "OP_PROF_SET", 0, [i, step, dur])
    add(r.cmd_rate(step), "OP_RATE", 0, [step])
add(r.cmd_prof_add(0, 1), "OP_PROF_ADD", 0, [0, 1])
add(r.cmd_prof_add(0xFFFFFFFF, r.DUR_MAX), "OP_PROF_ADD", 0, [0xFFFFFFFF, r.DUR_MAX])
add(r.cmd_prof_set(63, 0xFFFFFFFF, r.DUR_MAX), "OP_PROF_SET", 0, [63, 0xFFFFFFFF, r.DUR_MAX])

out = os.path.join(HERE, "rec_cmd_vectors.txt")
with open(out, "w", newline="\n") as f:
    f.write("// rec_cmd_vectors.txt: generated by gen_cmd_vectors.py from tools/recorder.py (do not edit)\n")
    f.write("// OPNAME SUB NARGS A0 A1 A2 | command text\n")
    f.write("\n".join(rows) + "\n")
print("%d vectors -> %s" % (len(rows), out))
