    // ---- clock / reset / status ----
    .sys_clk         (sys_clk),
    .sys_rst_n       (sys_rst_n),
    .user_clk_out    (user_clk_out),
    .user_reset_out  (user_reset_out),
    .user_lnk_up     (user_lnk_up),
    .user_app_rdy    (),

    // ---- AXI-S transmit ----
    .s_axis_tx_tdata  (s_axis_tx_tdata),
    .s_axis_tx_tkeep  (s_axis_tx_tkeep),
    .s_axis_tx_tlast  (s_axis_tx_tlast),
    .s_axis_tx_tvalid (s_axis_tx_tvalid),
    .s_axis_tx_tready (s_axis_tx_tready),
    .s_axis_tx_tuser  (s_axis_tx_tuser),
    .tx_buf_av        (tx_buf_av),
    .tx_cfg_req       (),
    .tx_cfg_gnt       (tx_cfg_gnt),
    .tx_err_drop      (),

    // ---- AXI-S receive ----
    .m_axis_rx_tdata  (m_axis_rx_tdata),
    .m_axis_rx_tkeep  (m_axis_rx_tkeep),
    .m_axis_rx_tlast  (m_axis_rx_tlast),
    .m_axis_rx_tvalid (m_axis_rx_tvalid),
    .m_axis_rx_tready (m_axis_rx_tready),
    .m_axis_rx_tuser  (m_axis_rx_tuser),
    .rx_np_ok         (rx_np_ok),         // IP generated with Receive_NP_Request = false
    .rx_np_req        (1'b1),             // on the port list, unused in rx_np_ok mode (Xilinx example: 1)

    // ---- flow-control credit monitor (not used) ----
    .fc_sel           (3'b000),
    .fc_cpld          (),
    .fc_cplh          (),
    .fc_npd           (),
    .fc_nph           (),
    .fc_pd            (),
    .fc_ph            (),

    // ---- configuration management (cfg_mgmt) ----
    .cfg_mgmt_di               (cfg_mgmt_di),
    .cfg_mgmt_byte_en          (cfg_mgmt_byte_en),
    .cfg_mgmt_dwaddr           (cfg_mgmt_dwaddr),
    .cfg_mgmt_wr_en            (cfg_mgmt_wr_en),
    .cfg_mgmt_rd_en            (cfg_mgmt_rd_en),
    .cfg_mgmt_do               (cfg_mgmt_do),
    .cfg_mgmt_rd_wr_done       (cfg_mgmt_rd_wr_done),
    .cfg_mgmt_wr_readonly      (cfg_mgmt_wr_readonly),
    .cfg_mgmt_wr_rw1c_as_rw    (cfg_mgmt_wr_rw1c_as_rw),

    // ---- configuration status outputs (not used) ----
    .cfg_status                (),
    .cfg_command               (),
    .cfg_dstatus               (),
    .cfg_dcommand              (),
    .cfg_lstatus               (),
    .cfg_lcommand              (),
    .cfg_dcommand2             (),
    .cfg_pcie_link_state       (),
    .cfg_pmcsr_pme_en          (),
    .cfg_pmcsr_powerstate      (),
    .cfg_pmcsr_pme_status      (),
    .cfg_received_func_lvl_rst (),
    .cfg_bus_number            (),
    .cfg_device_number         (),
    .cfg_function_number       (),
    .cfg_to_turnoff            (),
    .cfg_vc_tcvc_map           (),
    .cfg_bridge_serr_en        (),
    .cfg_slot_control_electromech_il_ctl_pulse      (),
    .cfg_root_control_syserr_corr_err_en            (),
    .cfg_root_control_syserr_non_fatal_err_en       (),
    .cfg_root_control_syserr_fatal_err_en           (),
    .cfg_root_control_pme_int_en                    (),
    .cfg_aer_rooterr_corr_err_reporting_en          (),
    .cfg_aer_rooterr_non_fatal_err_reporting_en     (),
    .cfg_aer_rooterr_fatal_err_reporting_en         (),
    .cfg_aer_rooterr_corr_err_received              (),
    .cfg_aer_rooterr_non_fatal_err_received         (),
    .cfg_aer_rooterr_fatal_err_received             (),

    // ---- received-message outputs (message routing disabled in the IP; not used) ----
    .cfg_msg_received                    (),
    .cfg_msg_data                        (),
    .cfg_msg_received_err_cor            (),
    .cfg_msg_received_err_non_fatal      (),
    .cfg_msg_received_err_fatal          (),
    .cfg_msg_received_pm_as_nak          (),
    .cfg_msg_received_pm_pme             (),
    .cfg_msg_received_pme_to_ack         (),
    .cfg_msg_received_assert_int_a       (),
    .cfg_msg_received_assert_int_b       (),
    .cfg_msg_received_assert_int_c       (),
