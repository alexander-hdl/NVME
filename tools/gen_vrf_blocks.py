#!/usr/bin/env python3
"""Reference blocks for tb_rec_verify (WP6): sim/vectors/vrf_blocks.hex.

Built with tools/rec_decode.py build_block (spec 3.1).  Layout of the file: N blocks x 256 lines,
128-bit hex per line (MSB first = $readmemh into logic [127:0]; byte 0 = bits [7:0]).
Block index == header pos (except 69, a deliberate duplicate of 62).  See BLOCKS below.
Usage: gen_vrf_blocks.py [OUT]       (self-checks every block with rec_decode.decode_block)
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rec_decode as rd

SID = 0xC0DE0001
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "sim", "vectors", "vrf_blocks.hex")


def fix_crc(b):
    b = bytearray(b)
    struct.pack_into("<I", b, 4088, rd.crc32(bytes(b[:rd.CRC_SPAN])))
    return bytes(b)


def clean(pos):
    """Block `pos` of the clean chain 0..63: lost=3 from pos 10 (DROP at 10), PAD/TRUNC/LAST at the end."""
    f = 0
    lost = 3 if pos >= 10 else 0
    valid = 252
    if pos == 0:
        f |= rd.FLAG_FIRST
    if pos == 10:
        f |= rd.FLAG_DROP
    if 20 <= pos < 30:
        f |= rd.FLAG_PROF
    if 30 <= pos < 40:
        f |= rd.FLAG_BP
    if pos == 58:
        f |= rd.FLAG_TRUNC
        valid = 100
    if pos >= 59:
        f |= rd.FLAG_PAD
        valid = 0
    if pos == 63:
        f |= rd.FLAG_LAST
    return rd.build_block(pos, sid=SID, ts=pos * 1000 + 7, flags=f, valid=valid, lost=lost,
                          ddr_kib=pos, seg=pos & 3, rep=pos >> 2)


def blocks():
    out = [clean(p) for p in range(64)]
    kw = dict(sid=SID, ts=5000)
    out.append(rd.build_block(64, magic=0xDEADBEEF, **kw))            # 64 bad magic
    out.append(rd.build_block(65, ver=2, **kw))                       # 65 bad ver
    b = bytearray(rd.build_block(66, **kw))                           # 66 bad crc (crc field flipped)
    b[4088] ^= 0x01
    out.append(bytes(b))
    b = bytearray(rd.build_block(67, **kw))                           # 67 payload bit flip, crc stale
    b[100 * 16 + 9] ^= 0x20                                           # beat 100, DW2, bit 13
    out.append(bytes(b))
    out.append(rd.build_block(68, seq=68 + 5, **kw))                  # 68 seq gap (seq-lost != pos)
    out.append(clean(62))                                             # 69 duplicate of block 62
    out.append(rd.build_block(70, sid=0x0BAD0BAD, ts=5000))           # 70 wrong sid
    out.append(rd.build_block(71, magic_end=0x12345678, **kw))        # 71 bad magic_end
    b = bytearray(rd.build_block(72, **kw))                           # 72 bad pos_lo (crc fixed)
    struct.pack_into("<I", b, 4084, 0x1234)
    out.append(fix_crc(b))
    b = bytearray(rd.build_block(73, **kw))                           # 73 bad seq_lo (crc fixed)
    struct.pack_into("<I", b, 4080, 0x4321)
    out.append(fix_crc(b))
    out.append(rd.build_block(74, valid=253, **kw))                   # 74 valid > 252
    return out


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else OUT
    bl = blocks()
    exp_err = {64: {"magic"}, 65: {"ver"}, 66: {"crc"}, 67: {"payload", "crc"}, 68: {"seq_lost_pos"},
               69: {"seq_lost_pos"}, 70: set(), 71: {"magic_end"}, 72: {"pos_lo"}, 73: {"seq_lo"},
               74: {"valid"}}
    for i, b in enumerate(bl):
        d = rd.decode_block(b)
        e = set(d["errors"])
        if i < 64:
            assert not e, (i, e)
        elif i == 69:
            assert d["pos"] == 62 and not e   # self-consistent copy; wrong only against its address
        else:
            assert e == exp_err[i], (i, e)
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", newline="\n") as f:
        f.write("// vrf_blocks.hex - generated by tools/gen_vrf_blocks.py (WP6); do not edit\n")
        f.write("// %d blocks x 256 lines x 128 bit (byte 0 = bits [7:0]); idx 0..63 clean chain sid C0DE0001,\n" % len(bl))
        f.write("// 64 magic 65 ver 66 crc 67 payload 68 seqgap 69 dup(of 62) 70 sid 71 magic_end 72 pos_lo 73 seq_lo 74 valid\n")
        for b in bl:
            for k in range(256):
                f.write("%032x\n" % int.from_bytes(b[16 * k:16 * k + 16], "little"))
    print("wrote", os.path.abspath(out), len(bl), "blocks")


if __name__ == "__main__":
    main()
